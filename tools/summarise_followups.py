#!/usr/bin/env python3
"""Collect the follow-up experiments (scripts/run_pending_followups.sh) into results/followups/summary.md + summary.json.

Metrics, as everywhere in this repository:
    SR      the agent's own STOP within 3 m (standard)         -- pointing: model_stop x "stopped within 3 m" / n
    end-SR  the episode ended within 3 m (STOP or step limit)  -- the evaluation scripts' "SR" field
    OS      within 3 m at any point
"""
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[1]
LOGS = ROOT / "logs" / "followups"
OUT = ROOT / "results" / "followups"


def parse_eval_log(path):
    txt = path.read_text(errors="replace")
    r = {}
    for k in ("SR", "SPL", "OS", "nDTW", "NE"):
        m = re.findall(rf"^\s+{k}\s+=\s+([0-9.]+)", txt, re.M)
        if m:
            r[k] = float(m[-1])
    n = re.search(r"episodes=(\d+)", txt)
    stops = re.search(r"^\s+model_stop\s+(\d+)\s+\(", txt, re.M)
    within = re.search(r"where it STOPPED.*within 3m\s+([0-9.]+)%", txt)
    if n:
        r["n"] = int(n.group(1))
    if stops:
        r["own_stops"] = int(stops.group(1))
    if n and stops and within:
        r["SR_stop"] = round(int(stops.group(1)) * float(within.group(1)) / 100) / int(n.group(1))
    return r


def pct(x):
    return "—" if x is None else f"{100 * x:.1f}"


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    rows, data = [], {}
    for log in sorted(LOGS.glob("cl_*.log")):
        r = parse_eval_log(log)
        data[log.stem] = r
        rows.append((log.stem, r.get("n"), r.get("SR_stop"), r.get("SR"), r.get("OS"), r.get("SPL"), r.get("NE")))
    for jf in sorted((ROOT / "results" / "runs").glob("v3_step1500_direct*.json")):
        d = json.loads(jf.read_text())
        data[jf.stem] = d
        rows.append((jf.stem, d.get("n_episodes"), d.get("SR_stop") if d.get("strict") else None,
                     d.get("SR") if d.get("strict") else None, d.get("OS"), d.get("SPL"), d.get("NE")))
    slot = ROOT / "results" / "slot_shortcut.json"
    if slot.exists():
        data["slot_shortcut"] = json.loads(slot.read_text())
    (OUT / "summary.json").write_text(json.dumps(data, indent=1))

    md = ["# Follow-up experiments: summary", "",
          "Generated by `tools/summarise_followups.py` from `logs/followups/` and `results/runs/`.", "",
          "SR = own STOP within 3 m (standard); end-SR = ended within 3 m; OS = within 3 m at any point. Percent.", "",
          "| item | n | SR | end-SR | OS | SPL* | NE (m) |", "|---|---|---|---|---|---|---|"]
    for name, n, sr, esr, os_, spl, ne in rows:
        md.append(f"| {name} | {n or '—'} | {pct(sr)} | {pct(esr)} | {pct(os_)} | {pct(spl)} | "
                  f"{'—' if ne is None else f'{ne:.2f}'} |")
    if "slot_shortcut" in data:
        md += ["", "## Held-out action accuracy by Pilot-slot content", "",
               "| model | true next frame | own latent | current frame | other episode's frame | no slot |",
               "|---|---|---|---|---|---|"]
        for k, v in data["slot_shortcut"].items():
            c = v["conditions"]
            g = lambda key: pct(c[key]["accuracy"]) if key in c else "—"
            md.append(f"| {k} | {g('next_frame')} | {g('own_z')} | {g('current_frame')} | {g('other_next_frame')} | "
                      f"{g('no_slot')} |")
    md += ["", "\\* SPL uses end-SR as its success criterion. Diagnostic runs (Stage 2, reasoner repeats) end on arrival, "
           "so only OS is meaningful for them."]
    (OUT / "summary.md").write_text("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
