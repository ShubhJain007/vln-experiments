#!/usr/bin/env bash
# D29: multi-layer fusion head (23, 26, 28) + stride-8 history, full 61-scan corpus.
#
# WHY: a per-layer probe (train-fit, val_unseen-scored) found the FINAL layer is
# the worst place to read the stop decision -- AUC 0.441, below chance -- while
# layer 23 reaches 0.694 and fusing gives 0.74-0.80. The deployed head was
# reading H[-1] only, which is why stop separation was stuck at 4-5x.
#
#     layers      u corr    act     stop AUC
#     28 (old)    0.317     0.407   0.442
#     23,26,28    ~0.30     ~0.55   ~0.74
#
# 1.5 epochs (~30 h). The previous run showed SR flat between 0.37 and 0.92
# epochs, so there is no reason to pay for 3 -- the question here is whether
# FUSION changes the ceiling, not whether more epochs do.
#
# Do NOT edit this file while it runs: sed -i writes a new inode and the running
# bash keeps executing the old one.
PY=${PY:-python}            # python of the latentpilot env (environment/latentpilot.yml)
cd "$(dirname "$0")/.." || exit 1
export PYTHONPATH="" HF_HUB_OFFLINE=1

STEPS=163300
echo "######## FUSION train started $(date) ########"
$PY -u src/train/train_pointing.py --steps $STEPS --batch-size 4 \
    --history-frames 2 --history-stride 8 \
    --fusion-layers 23 26 28 \
    --save-every 20000 --log-every 200 \
    --out checkpoints/pointing_fusion 2>&1 \
  | grep --line-buffered -v "it/s\]\|tied weights\|Loading weights"
echo "######## FUSION train finished $(date) ########"

for thr in 0.05 0.10 0.20; do
  echo "######## FUSION eval strict thr=$thr n=150 ########"
  $PY -u scripts/eval_pointing.py --checkpoint checkpoints/pointing_fusion/final \
      --split val_unseen --limit 150 --stop-threshold $thr --strict 2>&1 \
    | grep -v "Loading weights\|tied weights"
done
echo "######## FUSION COMPLETE $(date) ########"
